export function ticketProduct(id) {
 for (const event of L) {
  if (!id.startsWith(event.id + "-")) continue;
  const listing = generate(event).find(x => x.id === id);
  if (!listing) return null;
  const venue = T[event.venue];
  return { id, name: `${venue.name} · ${event.start} · ${listing.title} · ${listing.row ? "Row " + listing.row : "General admission"}`, kind: "ticket", price_cents: listing.price * 100, sizes: "[]", inventory: null, lo: listing.lo, hi: listing.hi };
 }
 return null;
}
